    private void itemRecuperarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemRecuperarDatosActionPerformed

        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Desea reemplazar los datos actuales por los guardados?",
                "Recuperar datos",
                JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {

            try {

                Sistema datosGuardados = Persistencia.recuperar();

                sistema.recuperarDatos(datosGuardados);

                JOptionPane.showMessageDialog(
                        this, "Datos recuperados correctamente.");

            } catch (IOException | ClassNotFoundException e) {

                JOptionPane.showMessageDialog(
                        this,
                        "No se pudieron recuperar los datos.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }
        }

    }//GEN-LAST:event_itemRecuperarDatosActionPerformed

