    @Override
    public void actualizar(Sistema sistema) {

        adopciones = sistema.getAdopciones();

        DefaultListModel<String> modelo = new DefaultListModel<>();

        for (Adopcion adopcion : adopciones) {

            modelo.addElement(
                    "N.º " + adopcion.getNumero() + " - "
                    + adopcion.getAnimal().getCodigo() + " - "
                    + adopcion.getAnimal().getNombre() + " - "
                    + adopcion.getFamilia().getApellido());
        }

        lstAdopciones.setModel(modelo);
    }

    @Override
    public void dispose() {

        if (sistema != null) {
            sistema.eliminarObservador(this);
        }

        super.dispose();
    }

