    private void btnAnularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAnularActionPerformed

        int indice = lstAdopciones.getSelectedIndex();

        if (indice == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar una adopción.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        Adopcion adopcion = adopciones.get(indice);

        int numero = adopcion.getNumero();

        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Desea anular la adopción número " + numero + "?",
                "Confirmar anulación",
                JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {

            if (sistema.anularAdopcion(numero)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Adopción anulada correctamente.");

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No se pudo anular la adopción.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }
        }

    }//GEN-LAST:event_btnAnularActionPerformed

