    private void btnAdoptarActionPerformed(java.awt.event.ActionEvent evt) {

        int indiceAnimal = lstAnimales.getSelectedIndex();
        int indiceFamilia = lstFamilias.getSelectedIndex();

        if (indiceAnimal == -1 || indiceFamilia == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un animal y una familia.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        Animal animal = animalesDisponibles.get(indiceAnimal);
        Familia familia = familias.get(indiceFamilia);

        String comentarios = txtComentarios.getText().trim();

        Adopcion adopcion = sistema.realizarAdopcion(
                animal.getCodigo(),
                familia.getCedula(),
                comentarios);

        if (adopcion != null) {

            lblNumeroAdopcion.setText(
                    String.valueOf(adopcion.getNumero()));

            txtComentarios.setText("");

            JOptionPane.showMessageDialog(
                    this,
                    "Adopcion realizada correctamente."
                    + "\nNumero de adopcion: "
                    + adopcion.getNumero());

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo realizar la adopcion.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    }

