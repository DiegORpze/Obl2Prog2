    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed

        int indice = lstEmpresas.getSelectedIndex();

        if (indice == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar una empresa.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        Empresa empresa = empresas.get(indice);

        int tipo = cmbTipoAlimento.getSelectedIndex() + 1;

        try {

            double kilos = Double.parseDouble(
                    txtKilos.getText().trim().replace(",", "."));

            Donacion donacion = sistema.registrarDonacion(
                    empresa.getRut(), tipo, kilos);

            if (donacion != null) {

                lblNumeroDonacion.setText(
                        String.valueOf(donacion.getNumero()));

                limpiarCampos();

                JOptionPane.showMessageDialog(
                        this,
                        "Donación registrada correctamente."
                        + "\nNúmero de donación: "
                        + donacion.getNumero());

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Los datos de la donación son incorrectos.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese una cantidad numérica válida.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnRegistrarActionPerformed

