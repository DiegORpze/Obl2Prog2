    @Override
    public void actualizar(Sistema sistema) {

        empresas = sistema.getEmpresas();

        DefaultListModel<String> modelo = new DefaultListModel<>();

        for (Empresa empresa : empresas) {

            modelo.addElement(
                    empresa.getRut() + " - "
                    + empresa.getNombre());
        }

        lstEmpresas.setModel(modelo);
    }

    private void limpiarCampos() {

        txtKilos.setText("");

        cmbTipoAlimento.setSelectedIndex(0);

        lstEmpresas.clearSelection();

        txtKilos.requestFocus();
    }

    @Override
    public void dispose() {

        if (sistema != null) {
            sistema.eliminarObservador(this);
        }

        super.dispose();
    }

