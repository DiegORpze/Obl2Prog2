    private void btnImportarActionPerformed(java.awt.event.ActionEvent evt) {

        if (archivoSeleccionado == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un archivo.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        try {

            String resultado = ImportadorDonaciones.importar(
                    archivoSeleccionado, sistema);

            txtResultado.setText(resultado);

            btnImportar.setEnabled(false);

        } catch (IOException e) {

            txtResultado.setText(
                    "Error durante la importación: "
                    + e.getMessage());

            btnImportar.setEnabled(false);

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo completar la importación.\n"
                    + "Es posible que se hayan registrado algunas donaciones.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    }

    private void btnCerrarActionPerformed(java.awt.event.ActionEvent evt) {
        dispose();
    }

    private void btnExaminarActionPerformed(java.awt.event.ActionEvent evt) {
        JFileChooser selector = new JFileChooser();

        selector.setDialogTitle("Seleccionar archivo de donaciones");

        selector.setFileFilter(
                new FileNameExtensionFilter("Archivos TXT", "txt"));

        int respuesta = selector.showOpenDialog(this);

        if (respuesta == JFileChooser.APPROVE_OPTION) {

            archivoSeleccionado = selector.getSelectedFile();

            txtArchivo.setText(archivoSeleccionado.getAbsolutePath());

            btnImportar.setEnabled(true);
        }

    }

