    @Override
    public void actualizar(Sistema sistema) {

        animalesNoEntregados = new ArrayList<>();

        DefaultListModel<String> modelo = new DefaultListModel<>();

        for (Animal animal : sistema.getAnimales()) {

            if (!Sistema.ENTREGADO.equals(animal.getEstado())) {

                animalesNoEntregados.add(animal);

                modelo.addElement(
                        animal.getCodigo() + " - "
                        + animal.getNombre() + " - "
                        + animal.getEstado());
            }
        }

        lstAnimales.setModel(modelo);
    }

    private void configurarColores() {

        lstAnimales.setCellRenderer(new DefaultListCellRenderer() {

            @Override
            public Component getListCellRendererComponent(
                    JList<?> list, Object value, int index,
                    boolean isSelected, boolean cellHasFocus) {

                Component componente
                        = super.getListCellRendererComponent(
                                list, value, index,
                                isSelected, cellHasFocus);

                String texto = value.toString();

                if (texto.endsWith(" - " + Sistema.DISPONIBLE)) {

                    componente.setForeground(new Color(0, 128, 0));

                } else if (texto.endsWith(" - " + Sistema.NO_DISPONIBLE)) {

                    componente.setForeground(Color.RED);
                }

                return componente;
            }
        });
    }

    @Override
    public void dispose() {

        if (sistema != null) {
            sistema.eliminarObservador(this);
        }

        super.dispose();
    }

