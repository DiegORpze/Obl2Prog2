    private String nombreTipoAlimento(int tipo) {

        String nombre;

        switch (tipo) {

            case 1:
                nombre = "Perros grandes";
                break;

            case 2:
                nombre = "Perros chicos";
                break;

            case 3:
                nombre = "Perros adultos";
                break;

            case 4:
                nombre = "Otra";
                break;

            default:
                nombre = "Desconocido";
                break;
        }

        return nombre;
    }

    @Override
    public void actualizar(Sistema sistema) {

        DefaultTableModel modelo
                = (DefaultTableModel) tblDonaciones.getModel();

        modelo.setRowCount(0);

        for (Donacion donacion : sistema.getDonacionesOrdenadas()) {

            Object[] fila = {
                donacion.getNumero(),
                donacion.getEmpresa().getRut(),
                donacion.getEmpresa().getNombre(),
                nombreTipoAlimento(donacion.getTipo()),
                donacion.getCantidadKilos()
            };

            modelo.addRow(fila);
        }
    }

    @Override
    public void dispose() {

        if (sistema != null) {
            sistema.eliminarObservador(this);
        }

        super.dispose();
    }

