    private void btnExaminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExaminarActionPerformed

        JFileChooser selector = new JFileChooser();

        selector.setDialogTitle("Seleccionar ubicación");

        selector.setFileSelectionMode(
                JFileChooser.DIRECTORIES_ONLY);

        int respuesta = selector.showOpenDialog(this);

        if (respuesta == JFileChooser.APPROVE_OPTION) {

            txtUbicacion.setText(
                    selector.getSelectedFile().getAbsolutePath());
        }

    }//GEN-LAST:event_btnExaminarActionPerformed

    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed

        String nombre = txtNombre.getText().trim();
        String ubicacion = txtUbicacion.getText().trim();

        if (nombre.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe ingresar un nombre para el archivo.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        if (nombre.matches(".*[\\\\/:*?\"<>|].*")) {

            JOptionPane.showMessageDialog(
                    this,
                    "El nombre contiene caracteres no permitidos.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        if (!nombre.toLowerCase().endsWith(".html")) {
            nombre += ".html";
        }

        if (ubicacion.isEmpty()) {
            ubicacion = System.getProperty("user.dir");
        }

        File carpeta = new File(ubicacion);

        if (!carpeta.isDirectory()) {

            JOptionPane.showMessageDialog(
                    this,
                    "La ubicación indicada no es válida.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        File archivo = new File(carpeta, nombre);

        if (archivo.exists()) {

            int respuesta = JOptionPane.showConfirmDialog(
                    this,
                    "El archivo ya existe. ¿Desea reemplazarlo?",
                    "Confirmar",
                    JOptionPane.YES_NO_OPTION);

            if (respuesta != JOptionPane.YES_OPTION) {
                return;
            }
        }

        try {

            GeneradorHTML.generar(archivo, sistema);

            archivoGenerado = archivo;

            btnAbrir.setEnabled(true);

            JOptionPane.showMessageDialog(
                    this,
                    "Página generada correctamente.\n"
                    + archivo.getAbsolutePath());

        } catch (IOException e) {

            archivoGenerado = null;

            btnAbrir.setEnabled(false);

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo generar la página.\n"
                    + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnGenerarActionPerformed

    private void btnAbrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirActionPerformed

        if (archivoGenerado == null || !archivoGenerado.isFile()) {

            JOptionPane.showMessageDialog(
                    this,
                    "No existe una página generada.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            btnAbrir.setEnabled(false);

            return;
        }

        try {

            if (Desktop.isDesktopSupported()
                    && Desktop.getDesktop().isSupported(
                            Desktop.Action.BROWSE)) {

                Desktop.getDesktop().browse(
                        archivoGenerado.toURI());

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No se puede abrir el navegador automáticamente.");
            }

        } catch (IOException | UnsupportedOperationException
                | SecurityException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo abrir la página.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnAbrirActionPerformed

