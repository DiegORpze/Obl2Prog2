    @Override
    public void actualizar(Sistema sistema) {

        ArrayList<Familia> familias;

        if (rdbApellido.isSelected()) {

            familias = sistema.getFamiliaOrdenadasPorApellido();

        } else {

            familias = sistema.getFamiliaOrdenadasPorCantAdopciones();
        }

        DefaultTableModel modelo
                = (DefaultTableModel) tblFamilias.getModel();

        modelo.setRowCount(0);

        for (Familia familia : familias) {

            int cantidad = sistema.cantidadAdopcionesFamilia(
                    familia.getCedula());

            Object[] fila = {
                familia.getCedula(),
                familia.getApellido(),
                familia.getCelular(),
                cantidad
            };

            modelo.addRow(fila);
        }
    }

    @Override
    public void dispose() {

        if (sistema != null) {
            sistema.eliminarObservador(this);
        }

        super.dispose();
    }

