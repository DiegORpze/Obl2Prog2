    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed

        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String temperamento = txtTemperamento.getText().trim();
        String estado = (String) cmbEstado.getSelectedItem();

        try {

            double peso = Double.parseDouble(
                    txtPeso.getText().trim().replace(",", "."));

            Animal animal = new Animal(
                    codigo, nombre, temperamento, peso, estado);

            if (sistema.agregarAnimal(animal)) {

                JOptionPane.showMessageDialog(
                        this, "Animal registrado correctamente.");

                limpiarCampos();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Datos incorrectos o código repetido.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un peso numérico válido.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnRegistrarActionPerformed

